import mongoose from 'mongoose';
import { jsonOptions } from './shared/json.js';
import { searchable } from './shared/searchable.js';
import { softDelete } from './shared/softDelete.js';

const { ObjectId } = mongoose.Schema.Types;

// A file attached to a ticket - when it was opened, or with a reply or note.
// The file itself is on disk (see services/upload.service.js); only these
// details are in the database.
const attachmentSchema = new mongoose.Schema(
  {
    fileName: { type: String, required: true, trim: true, maxlength: 255 },
    mimeType: { type: String, required: true },
    size: { type: Number, required: true },
    // Where it is stored, relative to UPLOAD_DIR. Never sent to clients.
    storedName: { type: String, required: true },
    // The reply or note it came with; none when it came with the ticket itself.
    messageId: { type: ObjectId },
    // From an internal note: staff only, like the note.
    internal: { type: Boolean, default: false },
    uploadedBy: { type: ObjectId, ref: 'User' },
    uploadedAt: { type: Date, default: Date.now },
  },
  {
    toJSON: {
      virtuals: true,
      versionKey: false,
      transform(doc, ret) {
        delete ret._id;
        delete ret.storedName;
        return ret;
      },
    },
  }
);

// A support request from a company. The company's details stay on the company;
// the ticket references it, the person who raised it and its customer record.
const ticketSchema = new mongoose.Schema(
  {
    // Generated by the server; never accepted from clients.
    ticketNumber: { type: String, required: true, unique: true, immutable: true },
    companyId: { type: ObjectId, ref: 'Company', required: true, index: true },
    contactId: { type: ObjectId, ref: 'Contact', index: true },
    // The company's customer record, filled in by the server when there is one.
    customerId: { type: ObjectId, ref: 'Customer', index: true },
    // Optional: the project it concerns (same company).
    projectId: { type: ObjectId, ref: 'Project', index: true },
    subject: { type: String, required: true, trim: true, maxlength: 200 },
    description: { type: String, trim: true, maxlength: 10000 },
    categoryId: { type: ObjectId, ref: 'TicketCategory', index: true },
    priorityId: { type: ObjectId, ref: 'TicketPriority', index: true },
    statusId: { type: ObjectId, ref: 'TicketStatus', required: true, index: true },
    assignedTo: { type: ObjectId, ref: 'User', index: true },
    attachments: [attachmentSchema],
    // Set by the server when the ticket enters a resolved / closed status.
    resolvedAt: { type: Date },
    closedAt: { type: Date },
    // Kept up to date by the server, for lists.
    replyCount: { type: Number, default: 0 },
    lastActivityAt: { type: Date, index: true },
    createdBy: { type: ObjectId, ref: 'User' },
  },
  {
    timestamps: true,
    toJSON: jsonOptions({
      omit: ['deletedAt'],
      aliases: {
        companyId: 'company',
        contactId: 'contact',
        customerId: 'customer',
        projectId: 'project',
        categoryId: 'category',
        priorityId: 'priority',
        statusId: 'status',
        assignedTo: 'assignedToUser',
        createdBy: 'createdByUser',
      },
    }),
  }
);

softDelete(ticketSchema);

// Found by global search on these fields.
searchable(ticketSchema, ['ticketNumber', 'subject']);

export default mongoose.model('Ticket', ticketSchema);
